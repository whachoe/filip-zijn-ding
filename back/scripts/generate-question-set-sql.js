#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const vm = require('vm');

function parseArgs(argv) {
  const args = {
    version: 1,
    mmtPath: path.resolve(__dirname, '../../front/js/mmt.js'),
    outPath: null,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];

    if (token === '--version' || token === '-v') {
      const next = argv[i + 1];
      if (!next || Number.isNaN(Number(next))) {
        throw new Error('Expected numeric value after --version');
      }
      args.version = Number(next);
      i += 1;
      continue;
    }

    if (token === '--mmt' || token === '-m') {
      const next = argv[i + 1];
      if (!next) {
        throw new Error('Expected file path after --mmt');
      }
      args.mmtPath = path.resolve(process.cwd(), next);
      i += 1;
      continue;
    }

    if (token === '--out' || token === '-o') {
      const next = argv[i + 1];
      if (!next) {
        throw new Error('Expected file path after --out');
      }
      args.outPath = path.resolve(process.cwd(), next);
      i += 1;
      continue;
    }

    throw new Error(`Unknown argument: ${token}`);
  }

  return args;
}

function findMatchingBracket(source, openIndex) {
  let depth = 0;
  let inString = false;
  let quote = '';
  let escaped = false;

  for (let i = openIndex; i < source.length; i += 1) {
    const ch = source[i];

    if (inString) {
      if (escaped) {
        escaped = false;
        continue;
      }

      if (ch === '\\') {
        escaped = true;
        continue;
      }

      if (ch === quote) {
        inString = false;
        quote = '';
      }

      continue;
    }

    if (ch === '\'' || ch === '"' || ch === '`') {
      inString = true;
      quote = ch;
      continue;
    }

    if (ch === '[') {
      depth += 1;
      continue;
    }

    if (ch === ']') {
      depth -= 1;
      if (depth === 0) {
        return i;
      }
    }
  }

  throw new Error('Could not find matching closing bracket');
}

function extractCategories(source) {
  const marker = 'let categories';
  const markerIndex = source.indexOf(marker);
  if (markerIndex < 0) {
    throw new Error('Could not find `let categories` in source');
  }

  const openIndex = source.indexOf('[', markerIndex);
  if (openIndex < 0) {
    throw new Error('Could not find categories array opening bracket');
  }

  const closeIndex = findMatchingBracket(source, openIndex);
  const arrayLiteral = source.slice(openIndex, closeIndex + 1);

  return vm.runInNewContext(`(${arrayLiteral})`);
}

function extractIndicators(source) {
  const regex = /indicators\[(\d+)\]\s*=\s*\[/g;
  const indicators = [];
  let match;

  while ((match = regex.exec(source)) !== null) {
    const categoryIndex = Number(match[1]);
    const assignmentStart = match.index + match[0].length - 1;
    const assignmentEnd = findMatchingBracket(source, assignmentStart);
    const arrayLiteral = source.slice(assignmentStart, assignmentEnd + 1);

    indicators[categoryIndex] = vm.runInNewContext(`(${arrayLiteral})`);
  }

  if (!indicators.length) {
    throw new Error('Could not find any indicators assignments in source');
  }

  return indicators;
}

function pickDollarTag(payload) {
  const base = '$mmt$';
  if (!payload.includes(base)) {
    return base;
  }

  for (let i = 1; i < 1000; i += 1) {
    const candidate = `$mmt${i}$`;
    if (!payload.includes(candidate)) {
      return candidate;
    }
  }

  throw new Error('Could not find a safe SQL dollar-quote tag');
}

function toJsonbLiteral(value) {
  const json = JSON.stringify(value, null, 2);
  const tag = pickDollarTag(json);
  return `${tag}\n${json}\n${tag}::jsonb`;
}

function buildSql(version, categories, indicators, sourcePath) {
  const categoriesLiteral = toJsonbLiteral(categories);
  const indicatorsLiteral = toJsonbLiteral(indicators);

  return [
    '-- Generated by back/scripts/generate-question-set-sql.js',
    `-- Source: ${sourcePath}`,
    `-- Generated at: ${new Date().toISOString()}`,
    '',
    'INSERT INTO question_sets (version, categories, indicators)',
    'VALUES (',
    `  ${version},`,
    `  ${categoriesLiteral},`,
    `  ${indicatorsLiteral}`,
    ')',
    'ON CONFLICT (version) DO UPDATE SET',
    '  categories = EXCLUDED.categories,',
    '  indicators = EXCLUDED.indicators,',
    '  created_at = NOW();',
    '',
  ].join('\n');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const source = fs.readFileSync(args.mmtPath, 'utf8');

  const categories = extractCategories(source);
  const indicators = extractIndicators(source);

  if (!Array.isArray(categories) || !Array.isArray(indicators)) {
    throw new Error('Parsed data is not an array');
  }

  if (categories.length !== indicators.length) {
    throw new Error(
      `Categories count (${categories.length}) does not match indicators count (${indicators.length}).`
    );
  }

  const sql = buildSql(args.version, categories, indicators, args.mmtPath);

  if (args.outPath) {
    fs.mkdirSync(path.dirname(args.outPath), { recursive: true });
    fs.writeFileSync(args.outPath, sql, 'utf8');
    console.log(`SQL written to ${args.outPath}`);
    return;
  }

  process.stdout.write(sql);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
